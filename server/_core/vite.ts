import express, { type Express } from "express";
import fs from "fs";
import { type Server } from "http";
import { nanoid } from "nanoid";
import path from "path";

export async function setupVite(app: Express, server: Server) {
  // Only called in development - dynamically import vite
  if (process.env.NODE_ENV !== "development") {
    console.warn("setupVite called in non-development environment");
    return;
  }

  // Dynamically import vite only in development
  // This import is NOT bundled by esbuild because it's only executed at runtime
  const { createServer: createViteServer } = await import("vite");
  
  const serverOptions = {
    middlewareMode: true,
    hmr: { server },
    allowedHosts: true as const,
  };

  // Use configFile path instead of importing the config module
  // This prevents esbuild from bundling vite.config.ts
  const viteConfigPath = path.resolve(
    import.meta.dirname,
    "../..",
    "vite.config.ts"
  );

  const vite = await createViteServer({
    configFile: viteConfigPath,
    server: serverOptions,
    appType: "custom",
  });

  app.use(vite.middlewares);
  app.use("*", async (req, res, next) => {
    const url = req.originalUrl;

    try {
      const clientTemplate = path.resolve(
        import.meta.dirname,
        "../..",
        "client",
        "index.html"
      );

      // always reload the index.html file from disk incase it changes
      let template = await fs.promises.readFile(clientTemplate, "utf-8");
      template = template.replace(
        `src="/src/main.tsx"`,
        `src="/src/main.tsx?v=${nanoid()}"`
      );
      const page = await vite.transformIndexHtml(url, template);
      res.status(200).set({ "Content-Type": "text/html" }).end(page);
    } catch (e) {
      vite.ssrFixStacktrace(e as Error);
      next(e);
    }
  });
}

export function resolveStaticDistPath(runtimeDirectory: string = import.meta.dirname) {
  // When the server is bundled, index.js lives directly in dist/. The frontend
  // generated by Vite is therefore always located in its public/ sibling.
  return path.resolve(runtimeDirectory, "public");
}

export function serveStatic(app: Express) {
  const distPath = resolveStaticDistPath();
  
  if (!fs.existsSync(distPath)) {
    console.error(
      `ERROR: Could not find the build directory: ${distPath}`
    );
    app.use(express.static("."));
  } else {
    console.log(`[Server] Serving static files from: ${distPath}`);
    app.use(express.static(distPath));
  }

  // Handle SPA routing - serve index.html for all routes that don't match static files
  app.get("*", (_req, res) => {
    const indexPath = path.resolve(distPath, "index.html");
    if (fs.existsSync(indexPath)) {
      console.log(`[Server] Serving index.html for route: ${_req.path}`);
      res.sendFile(indexPath);
    } else {
      console.error(`[Server] index.html not found at ${indexPath}`);
      res.status(404).send("Not found - index.html missing");
    }
  });
}
